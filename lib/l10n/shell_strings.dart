/// Strings this pass actually renders. Everything else stays English
/// until that widget is edited.
class ShellStrings {
  final String code;
  final Map<String, String> _pack;

  const ShellStrings._(this.code, this._pack);

  String call(String key) => _pack[key] ?? _en[key] ?? key;

  String rail(String path) => switch (path) {
        '/home' => this('home'),
        '/stats' => this('stats'),
        '/search' => this('search'),
        '/mixes' => this('mixLab'),
        '/liked' => this('liked'),
        '/albums' => this('albums'),
        '/artists' => this('artists'),
        '/playlists' => this('playlists'),
        '/podcasts' => this('podcasts'),
        '/downloads' => this('downloads'),
        '/friends' => this('friends'),
        '/settings' => this('settings'),
        _ => this('home'),
      };

  String section(String id) => switch (id) {
        'general' => this('general'),
        'playback' => this('playback'),
        'audio' => this('audio'),
        'downloads' => this('downloads'),
        'library' => this('library'),
        'lyrics' => this('lyrics'),
        'appearance' => this('appearance'),
        'lastfm' => 'Last.fm',
        'integrations' => this('integrations'),
        'sources' => this('sources'),
        'experimental' => this('experimental'),
        'about' => this('about'),
        _ => id,
      };

  static ShellStrings resolve(AppLanguage language, Locale platform) {
    if (language == AppLanguage.system) {
      final tag = platform.countryCode == null || platform.countryCode!.isEmpty
          ? platform.languageCode
          : '${platform.languageCode}-${platform.countryCode}';
      final resolved = AppLanguage.fromTag(tag);
      if (resolved == AppLanguage.system) {
        return ShellStrings._('en', _en);
      }
      return ShellStrings._(resolved.tag, _packs[resolved.tag] ?? _en);
    }
    return ShellStrings._(language.tag, _packs[language.tag] ?? _en);
  }
}

